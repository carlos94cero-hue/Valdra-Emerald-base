#!/usr/bin/env python3
"""Install Valdara's traveler intro into Emerald's existing source. Never builds a ROM.
Run after install_port.py and install_motion.py. Re-running is safe.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
MARKER = '/* VALDARA_TRAVELER_INTRO_V1 */'
EXPECTED_MAIN = '45fa12cfc09aecca3450cba05676b3930ba3f861'

def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('Expected one source anchor: ' + old[:100])
    return text.replace(old, new, 1)

def text_header(dialogue):
    def ctext(lines):
        return r'\n'.join(lines)
    welcome = r'\p'.join(ctext(p) for p in dialogue['welcome_pages']) + r'\p'
    texts = {'Welcome': welcome, 'Choose': ctext(dialogue['choose']),
             'Boy': dialogue['boy'], 'Girl': dialogue['girl'],
             'Name': ctext(dialogue['name']), 'Confirm': ctext(dialogue['confirm']),
             'Ready': ctext(dialogue['ready'])}
    return ('/* Generated by valdara/intro/install.py from dialogue.json. */\n'
            '#ifndef VALDARA_INTRO_TEXT_H\n#define VALDARA_INTRO_TEXT_H\n'
            + ''.join(f'static const u8 sText_Valdara{k}[] = _("{v}");\n'
                      for k, v in texts.items()) + '#endif\n')

def install(root=ROOT):
    root = Path(root)
    dialogue = json.loads((root / 'valdara/intro/dialogue.json').read_text())
    source = root / 'src/main_menu.c'
    original = source.read_text()
    text = original
    if MARKER not in text:
        raw = source.read_bytes()
        blob = hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()
        if blob != EXPECTED_MAIN:
            raise ValueError('main_menu.c has changed; review before applying: ' + blob)
        text = replace_once(text, '#include "mystery_gift_menu.h"',
                            '#include "mystery_gift_menu.h"\n#include "valdara_intro_text.h"\n' + MARKER)
        for old, new in [('gText_Birch_Welcome','sText_ValdaraWelcome'),
                         ('gText_Birch_BoyOrGirl','sText_ValdaraChoose'),
                         ('gText_Birch_WhatsYourName','sText_ValdaraName'),
                         ('gText_Birch_SoItsPlayer','sText_ValdaraConfirm'),
                         ('gText_BirchBoy','sText_ValdaraBoy'),
                         ('gText_BirchGirl','sText_ValdaraGirl')]:
            text = replace_once(text, old, new)
        text = replace_once(text,
            'birchSpriteId = AddNewGameBirchObject(0x88, 0x3C, 1);',
            '/* Native traveler portrait: hat, backpack and walking stick. */\n'
            '    birchSpriteId = CreateTrainerSprite(FacilityClassToPicIndex(FACILITY_CLASS_HIKER),\n'
            '        120, 60, 1, &gDecompressionBuffer[2 * TRAINER_PIC_SIZE]);')
        text = replace_once(text,
            'gTasks[taskId].func = Task_NewGameBirchSpeech_ThisIsAPokemon;',
            '/* No professor lecture or creature-release detour. */\n'
            '            gTasks[taskId].func = Task_NewGameBirchSpeech_StartBirchLotadPlatformFade;')
        # Keep the hidden mon slot allocated for Emerald's naming/cleanup paths.
        start = text.index('static void Task_NewGameBirchSpeech_WaitToShowBirch(u8 taskId)\n{')
        end = text.index('\nstatic void ', start + 10)
        segment = text[start:end]
        segment = replace_once(segment, 'gSprites[spriteId].x = 136;', 'gSprites[spriteId].x = 120;')
        text = text[:start] + segment + text[end:]
        old = '''            gSprites[gTasks[taskId].tPlayerSpriteId].oam.objMode = ST_OAM_OBJ_BLEND;
            NewGameBirchSpeech_StartFadeOutTarget1InTarget2(taskId, 2);
            NewGameBirchSpeech_StartFadePlatformIn(taskId, 1);
            gTasks[taskId].func = Task_NewGameBirchSpeech_SlidePlatformAway2;'''
        new = '''            /* Confirm the selected protagonist; do not return to Birch's lecture. */
            NewGameBirchSpeech_ClearWindow(0);
            StringExpandPlaceholders(gStringVar4, sText_ValdaraReady);
            AddTextPrinterForMessage(TRUE);
            gSprites[gTasks[taskId].tPlayerSpriteId].x = 120;
            gTasks[taskId].tBG1HOFS = 0;
            SetGpuReg(REG_OFFSET_BG1HOFS, 0);
            gTasks[taskId].tIsDoneFadingSprites = TRUE;
            gTasks[taskId].func = Task_NewGameBirchSpeech_ShrinkPlayer;'''
        text = replace_once(text, old, new)
        source.write_text(text)
    (root / 'src/valdara_intro_text.h').write_text(text_header(dialogue))
    # The same field traveler still gives the starter, not the intro.
    port = root / 'data/maps/PuertoBrisa/map.json'
    if not port.is_file():
        raise ValueError('Install the Puerto Brisa maps before the intro.')
    obj = json.loads(port.read_text())
    travelers = [n for n in obj['object_events'] if n.get('script') == 'PuertoBrisa_Elder']
    if len(travelers) != 1:
        raise ValueError('Expected exactly one starter-giving traveler.')
    travelers[0]['graphics_id'] = 'OBJ_EVENT_GFX_HIKER'
    port.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + '\n')
    scripts = root / 'valdara/port_scripts.inc'
    st = scripts.read_text()
    st = st.replace('anciano que está junto al cartel.', 'viajero junto al cartel.')
    scripts.write_text(st)
    report = {'intro': 'traveler -> welcome -> protagonist -> name -> Puerto Brisa',
              'creature_name': dialogue['creatures'], 'traveler_graphic': 'HIKER',
              'native_portraits_preserved': True,
              'starter_given_in_intro': False, 'rom_created': False,
              'source_sha256': hashlib.sha256(text.encode()).hexdigest()}
    out = root / 'dist'; out.mkdir(exist_ok=True)
    (out / 'intro_validation.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print('PASS: traveler intro installed; Nevarios; native protagonist/name flow; no ROM built')
    return report

if __name__ == '__main__':
    install()
